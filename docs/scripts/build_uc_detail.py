def wrap(text, width=36):
    """Переносит подпись по словам: PlantUML сам этого не делает."""
    words, lines, cur = text.split(' '), [], ''
    for w in words:
        if cur and len(cur) + 1 + len(w) > width:
            lines.append(cur)
            cur = w
        else:
            cur = (cur + ' ' + w).strip()
    if cur:
        lines.append(cur)
    return NL.join(lines)


class Edges(object):
    """Выдаёт устойчивые номера связей: унаследованные из LEGACY, новые с R101."""

    def __init__(self):
        self.known = dict(LEGACY)
        self.next_id = 101

    def num(self, src, dst, kind):
        key = (src, dst, kind)
        if key not in self.known:
            self.known[key] = self.next_id
            self.next_id += 1
        return self.known[key]

    def line(self, src, dst, kind, text):
        return ["' edge:R%03d" % self.num(src, dst, kind), text]


def build(n, edges):
    spec = SPEC[n]
    base = 'UC%d' % n
    name = 'UC_%d_Detail' % n
    title = 'UC-%d. %s' % (n, CATALOG[n])
    out = [HEADER.format(name=name, title=title).rstrip(chr(10)), '']

    for alias in spec.get('actors', []):
        label, stereo = ACTORS[alias]
        out.append('actor "%s" as %s%s' % (label, alias, (' ' + stereo) if stereo else ''))

    out.append('rectangle "ИС «Караваны»" as SystemBoundary {')
    shown = sorted(set([n] + list(spec.get('cat', []))))
    for k in shown:
        out.append('  usecase "%s" as UC%d' % (wrap('UC-%d. %s' % (k, CATALOG[k])), k))
    for k, label, _steps in spec.get('subs', []):
        out.append('  usecase "%s" as %s_%s'
                   % (wrap('UC-%d.%s. %s' % (n, k, label)), base, k))
    for k, label, _ep, _cond in spec.get('exts', []):
        out.append('  usecase "%s" as %s_%s'
                   % (wrap('UC-%d.%s. %s' % (n, k, label)), base, k))
    out.append('}')

    for src, dst, kind in spec.get('rel', []):
        arrow = '<<include>>' if kind == 'i' else '<<extend>>'
        out += edges.line(src, dst, kind, '%s ..> %s : %s' % (src, dst, arrow))
    for k, _label, _steps in spec.get('subs', []):
        sub = '%s_%s' % (base, k)
        out += edges.line(base, sub, 'i', '%s ..> %s : <<include>>' % (base, sub))
    for k, _label, _ep, _cond in spec.get('exts', []):
        sub = '%s_%s' % (base, k)
        out += edges.line(sub, base, 'e', '%s ..> %s : <<extend>>' % (sub, base))
    for src, dst in spec.get('assoc', []):
        out += edges.line(src, dst, 'a', '%s --> %s' % (src, dst))
    for child, parent in spec.get('gen', []):
        out += edges.line(child, parent, 'g', '%s --|> %s' % (child, parent))

    legend = []
    if spec.get('subs'):
        legend.append('  Части основного потока (include):')
        for k, label, steps in spec['subs']:
            legend.append('  UC-%d.%s — %s (%s).' % (n, k, label, steps))
    eps = []
    for src, dst, ep, cond in spec.get('eps', []):
        eps.append('  %s → %s / %s: %s' % (src.replace('UC', 'UC-'),
                                           dst.replace('UC', 'UC-'), ep, cond))
    for k, label, ep, cond in spec.get('exts', []):
        eps.append('  UC-%d.%s → UC-%d / %s: %s.' % (n, k, n, ep, cond))
    if eps:
        legend.append('  Точки расширения и условия:')
        legend += eps
    for line in spec.get('note', []):
        legend.append('  ' + line)
    if legend:
        out.append('legend bottom')
        out += legend
        out.append('endlegend')
    out.append('@enduml')
    return CRLF.join(out) + CRLF


def main():
    check = '--check' in sys.argv
    edges = Edges()
    changed = []
    for n in range(1, 35):
        text = build(n, edges)
        path = os.path.join(OUT_DIR, 'UC_%d_Detail.puml' % n)
        old = io.open(path, encoding='utf-8', newline='').read() if os.path.exists(path) else ''
        if old != text:
            changed.append(os.path.basename(path))
            if not check:
                with io.open(path, 'w', encoding='utf-8', newline='') as f:
                    f.write(text)
    print('связей всего: %d, из них новых: %d' % (len(edges.known), edges.next_id - 101))
    print('%s: %d из 34' % ('отличаются' if check else 'перезаписано', len(changed)))
    return 1 if (check and changed) else 0


if __name__ == '__main__':
    sys.exit(main())
