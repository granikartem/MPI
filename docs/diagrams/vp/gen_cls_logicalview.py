NAME = 'CLS_LogicalView'
FILL_PKG = 'Cr:253,253,253,255'      # #FDFDFD — фон пакета-слоя


def Q(tag):
    return '{%s}%s' % (NS, tag)


p = Project(NAME)
d = p.diagram(NAME, 'ClassDiagram')

nodes = {}     # key -> (модель, фигура)
geom = {}      # key -> (x, y, w, h)
order = []     # фигуры в порядке создания — FillColor дописывается последним


# ─── примитивы ───────────────────────────────────────────────────────
def pkg(key, name, x, y, w, h):
    m = p.model('Package', name=name, hint='PK_' + key)
    s = d.shape('Package', m, x, y, w, h, name=name, fill=FILL_PKG, caption=False,
                hint='SH_' + key)
    d.child_shapes(s)
    nodes[key] = (m, s)
    geom[key] = (x, y, w, h)
    order.append(s)
    return s


def box(key, name, attrs, x, y, w, h, parent=None, fill=FILL_GREY, stereo=None):
    """Класс или логический компонент: свойства — строками, как в .puml."""
    m = p.cls(name, stereotype=stereo, hint='CL_' + key)
    for a in attrs:
        p.attr(m, a, visibility='Unspecified', hint='AT_' + key)
    s = d.shape('Class', m, x, y, w, h, name=name, fill=fill, caption=False,
                parent=nodes[parent][1] if parent else None, hint='SH_' + key)
    nodes[key] = (m, s)
    geom[key] = (x, y, w, h)
    order.append(s)
    return s


def enum(key, name, literals, x, y, w, h, parent=None, fill=FILL_GREY):
    m = p.cls(name, stereotype='enumeration', hint='EN_' + key)
    for lit in literals:
        p.lit(m, lit, hint='EL_' + key)
    s = d.shape('Class', m, x, y, w, h, name=name, fill=fill, caption=False,
                parent=nodes[parent][1] if parent else None, hint='SH_' + key)
    nodes[key] = (m, s)
    geom[key] = (x, y, w, h)
    order.append(s)
    return s


def A(key, side, pos):
    """Точка на границе фигуры: pos — абсолютная координата вдоль этой границы."""
    x, y, w, h = geom[key]
    if side == 'top':
        return (pos, y)
    if side == 'bottom':
        return (pos, y + h)
    if side == 'left':
        return (x, pos)
    if side == 'right':
        return (x + w, pos)
    raise ValueError(side)


def _reset(el):
    """requestResetCaption у коннектора — без него не рисуются роли и кратности."""
    dep_el = ET.Element(Q('DiagramElementProperties'))
    for n in ('requestResetCaption', 'requestResetCaptionSize'):
        ET.SubElement(dep_el, Q('BooleanProperty'), {'name': n, 'value': 'true'})
    el.insert(0, dep_el)
    return el


def link(key, a, b, label=None, am=None, bm=None, agg=None, nav=False, pts=None):
    """Ассоциация. agg='Aggregation' / 'Composited' — у конца A.

    Подпись и кратности расставляет сам VP (requestResetCaption), поэтому
    маршрут подобран так, чтобы его середина попадала в свободное место.
    """
    ma, sa = nodes[a]
    mb, sb = nodes[b]
    m = p.assoc(ma, mb, name=label, a_mult=am, b_mult=bm,
                a_agg=agg or 'None', hint='AS_' + key)
    if nav:
        # IAssociationEnd: NAVIGABLE = 0, UNSPECIFIED = 1.
        for tag, val in (('FromEnd', '1'), ('ToEnd', '0')):
            props = m.el.find(Q(tag) + '/' + Q('Model') + '/' + Q('ModelProperties'))
            ET.SubElement(props, Q('IntegerProperty'),
                          {'name': 'navigable', 'value': val})
    cn = _reset(d.connector('Association', m, sa, sb, points=pts, hint='CN_' + key))
    if nav:
        # IAssociationUIModel.SHOW_NAVIGATION_ARROWS_SHOW_ALL_ARROWS_AND_CROSSES = 1.
        # Без него наконечник следует настройке диаграммы и не рисуется.
        ET.SubElement(cn.find(Q('DiagramElementProperties')), Q('IntegerProperty'),
                      {'name': 'showNavigationArrows', 'value': '1'})


def dep(key, a, b, label=None, pts=None, cap=None, cw=(200, 16)):
    """Зависимость ..> — подпись ставится вручную по координатам холста."""
    ma, sa = nodes[a]
    mb, sb = nodes[b]
    m = p.flow('Dependency', ma, mb, name=label, hint='DP_' + key)
    d.connector('Dependency', m, sa, sb, points=pts,
                caption_xy=cap, caption_wh=cw, hint='CN_' + key)


def note(key, text, x, y, w, h):
    m = p.note(text, hint='NO_' + key)
    s = d.shape('NOTE', m, x, y, w, h, caption=False, fill=FILL_NOTE, hint='SH_' + key)
    nodes[key] = (m, s)
    geom[key] = (x, y, w, h)
    order.append(s)


