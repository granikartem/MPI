"""CLS_LogicalView: диаграмма классов логического уровня (Logical View).

Содержание перенесено из docs/diagrams/sad/CLS_LogicalView.puml: пакеты-слои
presentation / application / domain / infrastructure и «внешние системы»,
внутри — логические компоненты со стереотипами «компонент» и «контракт»,
доменные классы со свойствами в деловых типах, перечисления, зависимости
(часть со стереотипом «access»), ассоциации с кратностями, заметка о правилах
взаимодействия слоёв и легенда.

Раскладка задаётся здесь.

  * слои идут сверху вниз: presentation → application → domain; infrastructure
    стоит справа, на уровне нижней половины application, «внешние системы»
    и легенда — под ней;
  * горизонтальные «коридоры»: полоса y = 470…600 (между presentation
    и application) несёт связи «access» к хранению данных, полоса
    y = 960…1140 (между application и domain) — остальные межслойные связи;
    каждая связь занимает свою строку, подпись лежит под линией;
  * вертикальные «коридоры»: x = 56/74/92 слева от всех пакетов и
    x = 1795…1885 между domain и infrastructure;
  * у каждой связи маршрут задан ПОЛНОСТЬЮ: первая точка лежит на границе
    исходной фигуры, последняя — на границе целевой. Иначе Visual Paradigm
    отбрасывает список точек целиком и прокладывает связь по-своему
    (проверено на этой же диаграмме);
  * у ассоциаций requestResetCaption обязателен ради кратностей, поэтому
    подпись ставит сам VP — в середину маршрута. Маршруты изогнуты так,
    чтобы середина попадала в свободное место;
  * zorder назначается обходом дерева в глубину: пакет, затем его дети.
  * точки маршрута отбрасываются целиком, если первая не лежит на границе исходной
    фигуры, а последняя — на границе целевой; «вниз» — это рост y, и точка с y меньше
    нижней грани источника попадает ВНУТРЬ фигуры и тоже рушит весь список;
  * подпись ассоциации VP ставит сам в середину маршрута — её положение считается
    по длине ломаной, поэтому маршрут подбирается так, чтобы середина пришлась
    в свободное место;
  * ширина Caption задаёт обрезку: в зазор 100 px подпись «роль инициатора» не влезает
    и схлопывается в «роль ...», поэтому маршрут уведён под «Роль участника».
"""
